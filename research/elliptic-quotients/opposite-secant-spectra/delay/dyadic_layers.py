"""Geometric certificates for two-adic local-square cancellation, by layers of explicit sublattices.

Forms.  A term is a positive definite ternary Gram matrix G with integral diagonal and 2G integral, with a sign.
A signed list S of terms stands for sum sign * theta_G.  S_0 is the four 3-neighbours of the parent, with signs
(+, +, -, -).

Two operations on one form G, both by exact residue enumeration.
  D(G): the vectors of norm divisible by 4.  With a = 1 when G is integral and a = 2 otherwise, membership is
        constant on cosets of 2^a L (Q(r + 2^a w) - Q(r) = 2^(a+1) B(r, w) + 4^a Q(w) = 0 mod 4).  The set is a union
        of cosets closed under all integer multiples, hence a union of the lattices 2^a L + Z r over its residues,
        and as a disjoint union of cyclic generator sets
            1_D = sum over cyclic C in D (1_C - 1_{2C}),  C <-> lattice 2^a L + Z r.
        Each such lattice has all norms divisible by 4, so dividing its form by 4 gives again a form of the stated
        type.  Hence U(4) theta_G = sum (theta_{C/2} - theta_{2C/2}).
  P(G): the vectors of norm 1 mod 8, constant on cosets of 2^b L with b = 2 (G integral) or 3, closed under odd
        multiples (u^2 = 1 mod 8) and containing no element of 2L.  Hence
            1_P = sum over cyclic C generated in P (1_C - 1_{2C}),  so P_2 theta_G = sum (theta_C - theta_{2C}).
Both decompositions depend only on the isometry class of G.  Cancellation: a signed list is reduced by grouping
terms into isometry classes (exact integral isometries, checked by T^t G T = G' and det T = +-1) and summing signs.

Certificate.  Let R_j be the reduced class vector of S_j, where S_{j+1} = D(S_j).  Then R_j represents U(4)^j h
exactly, and the reduced class vector of P(S_j) represents P_2 U(4)^j h.  The class-level map R -> D(R) is linear,
so once R_m lies in the rational span of R_0, ..., R_{m-1} every later R_j does too.  If the reduced P-vectors of
R_0, ..., R_{m-1} all vanish, then P_2 U(4)^j h = 0 for every j >= 0, i.e. every coefficient of h at a square of
Q_2 vanishes.  The parent transfer then gives equal elliptic quotient counts in every degree.  The proof uses
only isometries of explicit lattices: no coefficient bound.

Usage: python dyadic_layers.py [--cases i,j | --all-dyadic] [--controls]
                              [--write receipt.json | --verify receipt.json]
"""
