def as_matrix(rows):
    return pari.matrix(3, 3, [Fraction(x) if not isinstance(x, int) else x for r in rows for x in r])


def rows(G):
    return [[str(G[i, j]) for j in range(3)] for i in range(3)]


def norm(G, v):
    return sum(G[i, j] * v[i] * v[j] for i in range(3) for j in range(3))


def integral(G):
    return all(G[i, j].denominator() == 1 for i in range(3) for j in range(3))


def subgroup_union_terms(m, S):
    """Write 1_S, for S a union of subgroups of A = (Z/m)^3, as sum c_F 1_F over the intersection-closed family
    generated by the maximal subgroups contained in S (Moebius on that family); checked on every element of A.
    Subgroups are bitmasks over the m^3 residues."""
    elems = list(product(range(m), repeat=3))
    index = {e: i for i, e in enumerate(elems)}
    Smask = 0
    for x in S:
        Smask |= 1 << index[x]
    if not Smask:
        return []
    if not Smask & 1:
        raise ArithmeticError("Expected a union of subgroups.")
    add = [[index[tuple((a + b) % m for a, b in zip(x, y))] for y in elems] for x in elems]

    def close(mask, new):
        """Subgroup generated by the subgroup `mask` and the element `new`."""
        members = [i for i in range(len(elems)) if mask >> i & 1]
        out = mask
        cur = new
        while not out >> cur & 1:
            for i in members:
                out |= 1 << add[cur][i]
            cur = add[cur][new]
        return out

    cyclic = {}
    for i in range(len(elems)):
        if Smask >> i & 1:
            cyclic[i] = close(1, i)
    family = set(cyclic.values())
    frontier = list(family)
    while frontier:
        H = frontier.pop()
        rest = Smask & ~H
        i = 0
        while rest:
            if rest & 1:
                K = close(H, i)
                if K & ~Smask == 0 and K not in family:
                    family.add(K); frontier.append(K)
            rest >>= 1; i += 1
    maximal = [H for H in family if not any(H != K and H & ~K == 0 for K in family)]
    inter = set(maximal)
    changed = True
    while changed:
        changed = False
        for H in list(inter):
            for K in list(inter):
                if (H & K) not in inter:
                    inter.add(H & K); changed = True
    coeff = {}
    for F in sorted(inter, key=lambda b: bin(b).count("1"), reverse=True):
        coeff[F] = 1 - sum(c for F2, c in coeff.items() if F != F2 and F & ~F2 == 0)
    for i in range(len(elems)):
        if sum(c for F, c in coeff.items() if F >> i & 1) != (Smask >> i & 1):
            raise ArithmeticError("Moebius decomposition failed.")
    return [(c, [elems[i] for i in range(len(elems)) if F >> i & 1]) for F, c in coeff.items() if c]


def minimal_modulus(G, test, top):
    """Least 2^a (a <= top) such that test(norm) is constant on cosets of 2^a L, checked on residues mod 2^top."""
    M = 2 ** top
    vals = {r: test(norm(G, r)) for r in product(range(M), repeat=3)}
    for a in range(1, top + 1):
        m = 2 ** a
        if all(vals[r] == vals[tuple(x % m for x in r)] for r in vals):
            return m
    return M


def lattice_of(m, F):
    cols = [pari.Col([m * int(i == j) for i in range(3)]) for j in range(3)]
    cols += [pari.Col(list(x)) for x in F if any(x)]
    return pari.mathnf(pari.Mat(cols))


def D_terms(G):
    """U(4): vectors of norm divisible by 4, a union of sublattices; each divided by 4."""
    test = lambda n: n % 4 == 0
    m = minimal_modulus(G, test, 1 if integral(G) else 2)
    S = [r for r in product(range(m), repeat=3) if test(norm(G, r))]
    out = []
    for c, F in subgroup_union_terms(m, S):
        C = lattice_of(m, F)
        H = C.mattranspose() * G * C / 4
        if any(H[i, i].denominator() != 1 for i in range(3)) or (2 * H).denominator() != 1:
            raise ArithmeticError("A rescaled divisible sublattice left the admissible class of forms.")
        out.append((c, H))
    return out


def hull(G, test, top):
    """The sublattice K generated by the vectors of L whose norm satisfies test; the test set of K equals that of L."""
    m = minimal_modulus(G, test, top)
    X = [r for r in product(range(m), repeat=3) if test(norm(G, r))]
    if not X:
        return None
    C = lattice_of(m, X)
    return C.mattranspose() * G * C


COMPLEMENTS = [None] + [c for k in range(1, 5) for c in combinations((0, 4, 8, 12), k)]


def P_terms(G, choice=None):
    """P_2: vectors of norm 1 mod 8, written as 1_P = 1_{P u Z} - 1_Z.  Z must contain every even multiple of a
    unit-square vector and make both P u Z and Z unions of sublattices; then the identity is exact.
    choice None: Z = norms 0 mod 4.  choice A (a set of residues mod 16 among 0, 4, 8, 12): Z = even multiples
    of P together with the vectors whose norm mod 16 lies in A.  Validity is checked by the Moebius identity."""
    if choice is None:
        test = lambda n: (n % 8 == 1, n % 4 == 0)
        top = 2 if integral(G) else 3
    else:
        test = lambda n: (n % 8 == 1, n % 16 in choice)
        top = 3 if integral(G) else 4
    m = minimal_modulus(G, test, top)
    res = list(product(range(m), repeat=3))
    P = {r for r in res if norm(G, r) % 8 == 1}
    if not P:
        return []
    if choice is None:
        Z = {r for r in res if norm(G, r) % 4 == 0}
    else:
        Z = {r for r in res if norm(G, r) % 16 in choice}
        for r in P:
            for j in range(0, m, 2):
                Z.add(tuple(j * x % m for x in r))
    out = []
    for sign, S in ((1, P | Z), (-1, Z)):
        for c, F in subgroup_union_terms(m, S):
            C = lattice_of(m, F)
            out.append((sign * c, C.mattranspose() * G * C))
    return out


class Registry:
    """Isometry classes of forms, with exact isometries to a representative."""

    def __init__(self):
        self.reps = []                 # integral scaled forms
        self.buckets = defaultdict(list)

    @staticmethod
    def scaled(G):
        s = lcm(*(int(G[i, j].denominator()) for i in range(3) for j in range(3)))
        return 2 * s * G, 2 * s           # even scaling keeps the scale class well defined across forms

    def key(self, G):
        H, s = self.scaled(G)
        return (str(G.matdet()), tuple(int(x) for x in H.qfrep(12 * s, 1)))

    def classify(self, G):
        """Return (class index, T) with T^t rep T = G, T integral unimodular."""
        k = self.key(G)
        H, _ = self.scaled(G)
        for idx in self.buckets[k]:
            R, _ = self.scaled(self.reps[idx])
            T = H.qfisom(R)                              # T^t R T = H
            if T:
                if T.mattranspose() * self.reps[idx] * T != G or abs(T.matdet()) != 1:
                    raise ArithmeticError("An isometry failed its exact check.")
                return idx, T
        self.reps.append(G)
        self.buckets[k].append(len(self.reps) - 1)
        return len(self.reps) - 1, pari.matid(3)


def reduce(reg, terms, log):
    vec = defaultdict(int)
    for s, G in terms:
        idx, T = reg.classify(G)
        vec[idx] += s
        log.append([s, rows(G), idx, delay_census.matrix_entries(T)])
    return {k: v for k, v in vec.items() if v}


def in_span(vectors, v):
    """Is the class vector v a rational combination of the earlier vectors?  Returns (bool, coefficients)."""
    if not v:
        return True, []
    if not vectors:
        return False, None
    keys = sorted({k for w in vectors + [v] for k in w})
    n = len(vectors)
    A = pari.matrix(len(keys), n + 1, [(vectors[c].get(k, 0) if c < n else v.get(k, 0))
                                       for k in keys for c in range(n + 1)])
    K = pari.matker(A)
    for j in range(int(pari.matsize(K)[1])):
        last = K[n, j]
        if last != 0:
            coeffs = [-K[i, j] / last for i in range(n)]
            combo = defaultdict(lambda: Fraction(0))
            for c, w in zip(coeffs, vectors):
                for k, m in w.items():
                    combo[k] += Fraction(str(c)) * m
            if any(combo[k] != v.get(k, 0) for k in set(combo) | set(v)):
                raise ArithmeticError("Span relation failed its exact check.")
            return True, [str(c) for c in coeffs]
    return False, None


def describe(used):
    if used == "general":
        return "rational combination of unit-square sets of all sublattices containing 4L"
    if used == "relation span":
        return "rational span of decomposition relations"
    if used == "hull":
        return "sublattices generated by the unit-square vectors"
    if isinstance(used, dict):
        return {str(k): describe(v) for k, v in used.items()}
    return "norm 0 mod 4" if used is None else {"even_multiples_and_norms_mod_16": list(used)}


def mixed_complements(reg, R):
    """Choose a complement per isometry class so that the unit-square class vectors cancel (meet in the middle)."""
    idxs = sorted(R)
    options = []
    for idx in idxs:
        opts = []
        for choice in COMPLEMENTS:
            try:
                terms = [(R[idx] * s, G) for s, G in P_terms(reg.reps[idx], choice)]
            except ArithmeticError:
                continue
            vec = defaultdict(int)
            for s, G in terms:
                vec[reg.classify(G)[0]] += s
            key = tuple(sorted((k, v) for k, v in vec.items() if v))
            if key not in [o[1] for o in opts]:
                opts.append((choice, key))
        options.append(opts)
    half = len(idxs) // 2
    def sums(part):
        result = {}
        combos = [([], defaultdict(int))]
        for opts in part:
            new = []
            for chosen, vec in combos:
                for choice, key in opts:
                    v2 = defaultdict(int, vec)
                    for k, v in key:
                        v2[k] += v
                    new.append((chosen + [choice], v2))
            combos = new
            if len(combos) > 200000:
                return None
        for chosen, vec in combos:
            result.setdefault(tuple(sorted((k, v) for k, v in vec.items() if v)), chosen)
        return result
    left, right = sums(options[:half]), sums(options[half:])
    if left is None or right is None:
        return None
    for key, chosen in left.items():
        neg = tuple(sorted((k, -v) for k, v in key))
        if neg in right:
            choice = dict(zip(idxs, chosen + right[neg]))
            log_P = []
            terms = [(R[idx] * s, G) for idx in idxs for s, G in P_terms(reg.reps[idx], choice[idx])]
            if reduce(reg, terms, log_P):
                raise ArithmeticError("Mixed complement failed its recheck.")
            return choice, log_P
    return None


def relation_span(reg, R):
    """Unit-square cancellation modulo the relations between alternative decompositions.

    For each class with representative G, every valid decomposition (complement choice, applied to G or to its
    unit-square hull K, which has the same unit-square vectors) gives an exact expression of P_2 theta_G as a class
    vector.  Differences of two such vectors are exact theta identities.  If the signed vector of one chosen
    decomposition lies in the rational span of these differences, then P_2 of the signed sum vanishes."""
    base, rels, decomps = defaultdict(Fraction), [], {}
    for idx, mult in R.items():
        G = reg.reps[idx]
        K = hull(G, lambda n: n % 8 == 1, 2 if integral(G) else 3)
        vecs = []
        for src_name, src in (("lattice", G), ("hull", K)):
            if src is None:
                continue
            for choice in COMPLEMENTS:
                try:
                    terms = P_terms(src, choice)
                except ArithmeticError:
                    continue
                vec = defaultdict(int)
                for s, H in terms:
                    vec[reg.classify(H)[0]] += s
                vecs.append(((src_name, choice), {k: v for k, v in vec.items() if v}))
        if not vecs:
            raise ArithmeticError("No checked unit-square expression for an input isometry class.")
        decomps[idx] = vecs
        for k, v in vecs[0][1].items():
            base[k] += mult * v
        for _, v in vecs[1:]:
            d = {k: v.get(k, 0) - vecs[0][1].get(k, 0) for k in set(v) | set(vecs[0][1])}
            d = {k: x for k, x in d.items() if x}
            if d:
                rels.append(d)
    # index-two relations: 3 P_2 theta_N = sum over the seven index-2 sublattices K of P_2 theta_K
    def pvec(G):
        vec = defaultdict(int)
        for s, H in P_terms(G, None):
            vec[reg.classify(H)[0]] += s
        return vec
    pool = list(R)
    for level in range(INDEX_TWO_LEVELS):
        nxt = []
        for idx in pool:
            N = reg.reps[idx]
            if not integral(N):
                continue
            d = defaultdict(int)
            for k, v in pvec(N).items():
                d[k] += 3 * v
            for a in product(range(2), repeat=3):
                if not any(a):
                    continue
                # kernel of the functional a mod 2
                cols = [pari.Col([2 * int(i == j) for i in range(3)]) for j in range(3)]
                cols += [pari.Col(list(x)) for x in product(range(2), repeat=3)
                         if sum(p * q for p, q in zip(a, x)) % 2 == 0 and any(x)]
                C = pari.mathnf(pari.Mat(cols))
                K = C.mattranspose() * N * C
                kidx = reg.classify(K)[0]
                nxt.append(kidx)
                for k, v in pvec(K).items():
                    d[k] -= v
            d = {k: v for k, v in d.items() if v}
            if d:
                rels.append(d)
        pool = sorted(set(nxt))
    base = {k: v for k, v in base.items() if v}
    if not base:
        return True, decomps, []
    ok, coeffs = in_span(rels, base)
    return ok, decomps, coeffs


_SUB4 = None


def subgroups_mod4():
    global _SUB4
    if _SUB4 is None:
        seen = set()
        for a, d, f in product((1, 2, 4), repeat=3):
            for b, c, e in product(range(4), repeat=3):
                cols = [(a, 0, 0), (b, d, 0), (c, e, f)]
                seen.add(frozenset(tuple((x * cols[0][i] + y * cols[1][i] + z * cols[2][i]) % 4 for i in range(3))
                                   for x, y, z in product(range(4), repeat=3)))
        _SUB4 = sorted(seen, key=lambda S: (len(S), sorted(S)))
    return _SUB4


def general_identity(reg, R):
    """Most general layer-0 style test.  For each class G (integral) write the unit-square indicator on L/4L as an
    unknown rational combination of the indicators P cap K over all sublattices 4L <= K <= L.  P_2 theta_K equals
    P_2 theta of the unit-square hull of K, so terms are labelled by the isometry class of that hull.  Solve for
    combinations that reproduce 1_P exactly on every residue of every class and cancel class by class."""
    var, eqs, rhs = [], [], []
    idxs = [idx for idx in R]
    if any(not integral(reg.reps[idx]) for idx in idxs):
        return None
    Ps = {}
    for idx in idxs:
        G = reg.reps[idx]
        P = [x for x in product(range(4), repeat=3) if norm(G, x) % 8 == 1]
        Ps[idx] = P
        for si, S in enumerate(subgroups_mod4()):
            if not any(x in S for x in P):
                continue
            C = lattice_of(4, S)
            K = C.mattranspose() * G * C
            H = hull(K, lambda n: n % 8 == 1, 2)
            var.append((idx, si, reg.classify(H)[0], rows(H)))
    if not var:
        return {"variables": [], "coefficients": []}
    for idx in idxs:
        for x in Ps[idx]:
            eqs.append([1 if (v[0] == idx and x in subgroups_mod4()[v[1]]) else 0 for v in var]); rhs.append(1)
    for cl in sorted({v[2] for v in var}):
        eqs.append([R[v[0]] if v[2] == cl else 0 for v in var]); rhs.append(0)
    A = pari.matrix(len(eqs), len(var), [e for row in eqs for e in row])
    K = pari.matker(pari.concat(A, -pari.Col(rhs)))
    n = len(var)
    for j in range(int(pari.matsize(K)[1])):
        if K[n, j] != 0:
            sol = [K[t, j] / K[n, j] for t in range(n)]
            # exact recheck of both families of equations
            for row, b in zip(eqs, rhs):
                if sum(sv * e for sv, e in zip(sol, row)) != b:
                    raise ArithmeticError("General identity failed its recheck.")
            return {"variables": [[str(v[0]), v[1], v[2]] for v in var],
                    "coefficients": [str(c) for c in sol]}
    return None


def certify_case(entry):
    parent, theta, _primes = case_data(entry)
    if "simultaneously_local_square" in entry:
        witness = entry["simultaneously_local_square"]
        n = witness["norm"]
        if (n <= 0 or not local_square(n, 2) or not witness["signed_coefficient"]
                or 2 * theta.through(n)[n-1] != witness["signed_coefficient"]):
            raise ArithmeticError("The archived control has no certified nonzero square coefficient.")
        return None, int(pari.valuation(n, 2)) // 2
    _, a, b, c, u, v, w = parent[0]
    gram = delay_census.gram_matrix(((a, u, v), (u, b, w), (v, w, c)))
    S = []
    for edge, sign in zip(parent[1], (1, -1), strict=True):
        for point in edge:
            B = neighbour_basis(gram, 3, point)
            S.append((sign, B.mattranspose() * gram * B))
    reg = Registry()
    layers = []
    R_vectors = []
    current = S
    for j in range(MAX_LAYERS):
        log_R = []
        R = reduce(reg, current, log_R)
        closed, relation = in_span(R_vectors, R)
        if closed:
            layers.append({"layer": j, "reduced": {str(k): m for k, m in R.items()}, "terms": log_R,
                           "relation_to_previous_layers": relation})
            return {"layers": layers, "classes": [rows(G) for G in reg.reps]}, j
        # P-part of the reduced vector: decompose one representative per class with multiplicity
        P, used = None, None
        log_P = []
        hulls = []
        for idx, mult in R.items():
            G0 = reg.reps[idx]
            K = hull(G0, lambda n: n % 8 == 1, 2 if integral(G0) else 3)
            if K is not None:
                hulls.append((mult, K))
        if not reduce(reg, hulls, log_P):
            P, used = {}, "hull"
        for choice in ([] if P is not None else COMPLEMENTS):
            log_P = []
            try:
                Pterms = [(m * s, G) for idx, m in R.items() for s, G in P_terms(reg.reps[idx], choice)]
            except ArithmeticError:
                continue
            if not reduce(reg, Pterms, log_P):
                P, used = {}, choice
                break
        if P is None:
            mixed = mixed_complements(reg, R)
            if mixed is not None:
                used, log_P = mixed
                P = {}
        if P is None:
            gen = general_identity(reg, R)
            if gen is not None:
                used, log_P, P = "general", gen, {}
        if P is None:
            ok, decomps, coeffs = relation_span(reg, R)
            if not ok:
                return None, j
            used = "relation span"
            log_P = {"decompositions": {str(k): [[describe(c[1]) if c[0] == "lattice" else ["hull", describe(c[1])], v]
                                                  for c, v in vs] for k, vs in decomps.items()},
                     "relation_coefficients": coeffs}
            P = {}
        Dterms = [(m * s, G) for idx, m in R.items() for s, G in D_terms(reg.reps[idx])]
        layers.append({"layer": j, "reduced": {str(k): m for k, m in R.items()}, "terms": log_R,
                       "unit_square_complement": describe(used), "unit_square_terms": log_P})
        R_vectors.append(R)
        current = Dterms
    return None, MAX_LAYERS


def check_partitions(records, path):
    """Check a positive partition and the exact isometry of each matched piece."""
    examples = json.loads(path.read_text())
    if set(examples) != {"71", "84", "100", "102", "111"}:
        raise ArithmeticError("The partition certificates do not cover the hard cases.")
    residues = tuple(product(range(4), repeat=3))
    unit_hulls = {}
    for index, pairs in examples.items():
        _, theta, _ = case_data(records[int(index)])
        forms = theta.forms
        if not all(integral(G) for G in forms):
            raise ArithmeticError("Expected integral Gram matrices for these partitions.")
        unit_sets = [{r for r in residues if norm(G, r) % 8 == 1} for G in forms]
        assigned = [set() for _ in forms]
        unit_hulls[index] = [hull(G, lambda n: n % 8 == 1, 2) for G in forms]
        expected = 2 if index == "111" else 1
        for i, j in product(range(2), range(2, 4)):
            if sum(item["left"][0] == i and item["right"][0] == j for item in pairs) != expected:
                raise ArithmeticError("Unexpected multiplicity in the matched pieces.")
        for pair in pairs:
            pieces = []
            for name in ("left", "right"):
                v, entries = pair[name]
                if v not in ((0, 1) if name == "left" else (2, 3)):
                    raise ArithmeticError("A matched piece belongs to the wrong side.")
                C = as_matrix(entries)
                if not C.matdet() or not integral(C):
                    raise ArithmeticError("A proposed sublattice has no full integral basis.")
                inverse = C**-1
                if not integral(4 * inverse):
                    raise ArithmeticError("A partition sublattice does not contain 4L.")
                part = {r for r in unit_sets[v]
                        if all(e.denominator() == 1 for e in inverse * pari.Col(r))}
                if not part or part & assigned[v]:
                    raise ArithmeticError("A unit-square piece is empty or overlaps another.")
                assigned[v].update(part)
                hull_basis = lattice_of(4, sorted(part))
                pieces.append((len(part), hull_basis.mattranspose() * forms[v] * hull_basis))
            (n, G), (m, H) = pieces
            T = as_matrix(pair["isometry"])
            if ([n, m] != pair["unit_residue_counts"] or abs(T.matdet()) != 1 or not integral(T)
                    or T.mattranspose() * G * T != H):
                raise ArithmeticError("A matched unit-square isometry failed.")
        if assigned != unit_sets:
            raise ArithmeticError("A unit-square residue is missing from the partition.")

        # Nonzero ordinary coefficients witness all pairwise differences even in
        # each of the eight progressions within the unit-square residues modulo 64.
        counts = [G.qfrep(512) for G in forms]
        for left, right in combinations(counts, 2):
            for r in range(1, 64, 8):
                if not any(left[n-1] != right[n-1] for n in range(r, 513, 64)):
                    raise ArithmeticError("No pairwise difference was witnessed in a progression.")
        print(f"{index}: {len(pairs)} matched pieces and 48 pairwise progression witnesses verified")
    for a, b, permutation in (("71", "100", (0, 1, 3, 2)), ("84", "102", (3, 2, 0, 1))):
        for G, j in zip(unit_hulls[a], permutation, strict=True):
            H = unit_hulls[b][j]
            T = H.qfisom(G)
            if not T or abs(T.matdet()) != 1 or T.mattranspose() * G * T != H:
                raise ArithmeticError("The cross-case unit-square hull isometry failed.")
    families = {unit_hulls[index][0].matdet() for index in ("71", "84", "111")}
    if len(families) != 3:
        raise ArithmeticError("Expected three distinct unit-square hull determinants.")
    print("The five cases have three distinct collections of unit-square hulls, up to signs.")


def check_controls(records):
    controls = [(i, e) for i, e in enumerate(records) if "simultaneously_local_square" in e]
    if len(controls) != 13:
        raise ArithmeticError("Expected thirteen nonvanishing controls.")
    for index, entry in controls:
        certificate, _ = certify_case(entry)
        if certificate is not None:
            raise ArithmeticError(f"The dyadic solver accepted the nonvanishing control at index {index}.")
    print("All thirteen exact nonvanishing controls rejected.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--cases", default="")
    scope.add_argument("--all-dyadic", action="store_true")
    parser.add_argument("--controls", action="store_true", help="also check nonvanishing and four-neighbour controls")
    parser.add_argument("--write", type=Path)
    parser.add_argument("--verify", type=Path)
    args = parser.parse_args()
    here = Path(__file__).parent
    records = json.loads((here / "local-square.json").read_text())
    done = {c["case"] for c in json.loads((here / "local-geometry.json").read_text())["dyadic_cases"]}
    todo = [i for i, e in enumerate(records)
            if any(t["prime"] == 2 for t in e.get("local_obstructions", []))
            and (args.all_dyadic or i not in done)]
    if args.all_dyadic and len(todo) != 90:
        raise ArithmeticError("Expected ninety dyadic cases in the input census.")
    if args.cases:
        todo = [int(x) for x in args.cases.split(",")]
    out, failed = {}, []
    for i in todo:
        cert, depth = certify_case(records[i])
        print(i, records[i]["parent"], "closed at layer" if cert else "FAILED at layer", depth, flush=True)
        if cert:
            out[str(i)] = {"parent": records[i]["parent"], "edges": records[i]["edges"], **cert}
        else:
            failed.append(i)
    summary = {"certified": sorted(map(int, out)), "failed": failed}
    print(json.dumps(summary))
    if args.write:
        args.write.write_text(json.dumps({"summary": summary, "cases": out}) + "\n")
    if args.verify:
        if json.loads(args.verify.read_text()) != json.loads(json.dumps({"summary": summary, "cases": out})):
            raise ArithmeticError("The layer replay differs from its receipt.")
        print("verified")
    if not args.cases and failed:
        raise ArithmeticError("A dyadic census case did not close.")
    if args.controls:
        check_partitions(records, here / "dyadic-partitions.json")
        check_controls(records)


if __name__ == "__main__":
    main()
