"""Exact observed fractions of gluing-pair differences, from the product formula.

Observed space (function side, mass inner product <f,g> = sum m_x f(x) g(x)) is the cyclic Hecke module
O = H . 1_R generated by the product classes R (v_0 = 2 . 1_R).  For a pair (i, j) the evaluation
difference is represented by g = delta_i/m_i - delta_j/m_j, ||g||^2 = 1/m_i + 1/m_j, and the observed
fraction is ||P_O g||^2 / ||g||^2.  Computing O with the Hecke operators of finitely many primes gives a
subspace of the true O, so the reported minimum is a rigorous lower bound (exact rationals)."""
import itertools, json, sys
sys.path.insert(0, "../inverse-spectrum")
from fractions import Fraction as Fr
import cypari2
from twins import closure_and_matrices, krylov_dim
from discform import isomorphic as disc_iso
from inverse import mat

pari = cypari2.Pari()
pari.allocatemem(8 * 10 ** 9)


def cyclic_module(v, ops):
    M = v
    r = int(pari.matrank(M))
    while True:
        B = pari.matimage(pari.matconcat([M] + [op * M for op in ops]))
        r2 = int(pari.matsize(B)[1])
        if r2 == r:
            return B
        M, r = B, r2


def run(d, l, primes, gluing_labels=None):
    classes, ng, A = closure_and_matrices(d, l, primes)
    n = len(classes)
    aut = [int(pari.qfauto(mat(q))[0]) for q in classes]          # m_x = 1/aut_x
    r1 = [2 * int(pari.qfrep(mat(q), 1)[0]) for q in classes]
    R = [x for x in range(n) if r1[x]]
    ops = [A[p] for p in primes]
    O = cyclic_module(pari.matrix(n, 1, [1 if x in R else 0 for x in range(n)]), ops)
    gen, reps = [], []
    for q in classes:
        for gi, rr in enumerate(reps):
            if disc_iso(rr, q):
                gen.append(gi); break
        else:
            reps.append(q); gen.append(len(reps) - 1)
    # restriction of O to each genus: the observed space for pairs inside that genus
    Og, Wg, Gig, idxg = {}, {}, {}, {}
    for g in range(len(reps)):
        idx = [x for x in range(n) if gen[x] == g]
        Rg = pari.matrix(len(idx), n, [1 if idx[a] == x else 0 for a in range(len(idx)) for x in range(n)])
        B = pari.matimage(Rg * O)
        kk = int(pari.matsize(B)[1])
        W = pari.matrix(len(idx), len(idx), [0] * (len(idx) ** 2))
        for a, x in enumerate(idx):
            W[a, a] = pari("1/%d" % aut[x])
        Og[g], Wg[g], idxg[g] = B, W, idx
        Gig[g] = pari.matsolve(pari.mattranspose(B) * W * B, pari.matid(kk))
    k = {g: int(pari.matsize(Og[g])[1]) for g in Og}
    worst = None
    fracs = []
    for i, j in itertools.combinations(range(ng), 2):
        if gen[i] != gen[j]:
            continue
        G_ = gen[i]
        idx = idxg[G_]
        g = pari.matrix(len(idx), 1, [aut[x] if x == i else (-aut[x] if x == j else 0) for x in idx])
        b = pari.mattranspose(Og[G_]) * Wg[G_] * g
        obs = (pari.mattranspose(b) * Gig[G_] * b)[0, 0]
        tot = aut[i] + aut[j]
        fr = Fr(str(obs)) / tot
        fracs.append(fr)
        if worst is None or fr < worst[0]:
            worst = (fr, classes[i], classes[j])
    return {"d": d, "l": l, "primes": primes, "closure": n, "gluing": ng, "products": len(R), "dim_O_per_genus": [k[g] for g in sorted(k)], "genus_sizes": [len(idxg[g]) for g in sorted(idxg)],
            "same_genus_pairs": len(fracs), "min_observed_fraction": str(worst[0]) if worst else None,
            "min_float": float(worst[0]) if worst else None, "worst_pair": [worst[1], worst[2]] if worst else None,
            "all_ge_half": all(f >= Fr(1, 2) for f in fracs)}


if __name__ == "__main__":
    out = []
    for spec in sys.argv[1:]:
        d, l, ps = spec.split(":")
        res = run(int(d), int(l), [int(x) for x in ps.split(",")])
        out.append(res)
        print({k: v for k, v in res.items() if k != "worst_pair"}, flush=True)
    json.dump(out, open("../walk-to-products/observed_fraction.json", "w"), indent=1)
