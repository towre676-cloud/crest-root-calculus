"""Structural separation certificate.  Within one genus, the square kernel K_g is a Hecke submodule.
If e_i - e_j were in K_g, the whole Hecke module generated by e_i - e_j would be.  So
    dim H<e_i - e_j>  >  dim K_g
certifies (without any witness degree) that the classes i, j are not square-equivalent.
We compute, per genus, dim K_g and min over pairs of dim H<e_i - e_j> (Krylov closure under T(p^2), T(p'^2))."""
import json, sys, glob, itertools
import cypari2
from hecke import neighbours, classify, mat
from discform import isomorphic as disc_iso

pari = cypari2.Pari()


def closure_and_matrices(d, l, primes):
    forms = []
    for f in glob.glob("inert_*.json"):
        for R in json.load(open(f)):
            if (R["d"], R["l"]) == (d, l):
                for g in R["genera"]:
                    forms += [x["q"] for x in g["forms"]]
    classes, buckets = [], {}
    for q in forms:
        classify(q, classes, buckets)
    ng = len(classes)
    rows = {p: {} for p in primes}
    changed = True
    while changed:
        changed = False
        for p in primes:
            for i in range(len(classes)):
                if i not in rows[p]:
                    rows[p][i] = [classify(q, classes, buckets) for q in neighbours(classes[i], p)]
                    changed = True
    n = len(classes)
    A = {p: pari.matrix(n, n, [sum(1 for j in rows[p][i] if j == k) for i in range(n) for k in range(n)]) for p in primes}
    return classes, ng, A


def krylov_dim(vecs, ops):
    M = pari.matconcat(vecs)
    r = int(pari.matrank(M))
    while True:
        new = pari.matconcat([M] + [op * M for op in ops])
        B = pari.matimage(new)
        r2 = int(pari.matsize(B)[1])
        if r2 == r:
            return r
        M, r = B, r2


def run(d, l, primes, Bsq=300):
    classes, ng, A = closure_and_matrices(d, l, primes)
    n = len(classes)
    gen, reps = [], []
    for q in classes:
        for gi, r in enumerate(reps):
            if disc_iso(r, q):
                gen.append(gi); break
        else:
            reps.append(q); gen.append(len(reps) - 1)
    ops = [pari.mattranspose(A[p]) for p in primes]
    S = []
    for q in classes:
        r = pari.qfrep(mat(q), Bsq * Bsq)
        S.append([int(r[m * m - 1]) for m in range(1, Bsq + 1)])
    res = {"d": d, "l": l, "primes": primes, "closure": n, "gluing": ng, "genera": []}
    for g in range(len(reps)):
        idx = [i for i in range(n) if gen[i] == g]
        M = pari.matrix(Bsq, len(idx), [S[j][i] for i in range(Bsq) for j in idx])
        kg = int(pari.matsize(pari.matker(M))[1])
        dims = []
        for i, j in itertools.combinations(idx, 2):
            if i >= ng or j >= ng:
                continue                       # only gluing classes matter for the inverse problem
            v = pari.matrix(n, 1, [1 if k == i else (-1 if k == j else 0) for k in range(n)])
            dims.append(krylov_dim([v], ops))
        res["genera"].append({"closure_size": len(idx), "K_within": kg,
                              "min_Hecke_module_dim_of_pair": min(dims) if dims else None,
                              "pairs": len(dims),
                              "certified_by_Hecke": (min(dims) > kg) if dims else None})
    return res


if __name__ == "__main__":
    out = []
    for spec in sys.argv[1:]:
        d, l, ps = spec.split(":")
        r = run(int(d), int(l), [int(x) for x in ps.split(",")])
        out.append(r)
        print(r, flush=True)
    json.dump(out, open("twins_results.json", "w"), indent=1)
