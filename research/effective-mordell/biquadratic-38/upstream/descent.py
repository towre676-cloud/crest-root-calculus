"""Complete 2-descent over a number field F for y^2 = (x-e1)(x-e2)(x-e3) with e_i in F.

The local images are generated by points of E(F_v) until they reach the known size
#E(F_v)[2] * |2|_v^{-1}; Selmer membership is then exact.  The upper bound on the rank is
dim Sel - 2.
"""
import random
from itertools import product
from cypari2 import Pari

pari = Pari(); pari.allocatemem(2*10**9)
pari("zz")  # created before any field variable, so it has higher priority


class Field:
    def __init__(self, pol):
        self.pol = pari(pol)
        self.bnf = pari.bnfinit(self.pol, 1)
        self.var = pari.variable(self.pol)

    def M(self, a):
        return pari.Mod(pari(a), self.pol)

    def lift(self, a):
        return pari.lift(self.M(a))

    def local_square(self, a, P):
        a = self.lift(a)
        return a == 0 or bool(pari.nfislocalpower(self.bnf, P, a, 2))

    def is_square(self, a):
        a = self.lift(a)
        return a == 0 or len(pari.nfroots(self.bnf, pari('zz^2') - a)) > 0

    def selmer_basis(self, primes):
        """F2-basis of F(S,2): torsion unit, fundamental units, S-unit generators."""
        tu = pari('(b)->b.tu')(self.bnf)
        fu = pari('(b)->b.fu')(self.bnf)
        gens = [self.M(tu[1])] + [self.M(u) for u in fu] + [self.M(g) for g in pari.bnfsunit(self.bnf, primes)[0]]
        return gens


def kummer(x, es, F):
    """Image of a point with abscissa x under x -> (x-e1, x-e2) (torsion-corrected)."""
    e1, e2, e3 = es
    out = []
    for i, e in enumerate((e1, e2)):
        if x == e:
            others = [f for f in es if f != e]
            v = (e - others[0])*(e - others[1])
        else:
            v = x - e
        out.append(F.M(v))
    return tuple(out)


def local_image(F, es, P, rng):
    """Generators of the image of E(F_v)/2E(F_v) in (F_v^*/F_v^*2)^2."""
    p = int(P.pr_get_p()); f = int(P.pr_get_f()); e = int(P.pr_get_e())
    target = 4 * (2**(e*f) if p == 2 else 1)
    pi = F.M(pari.nfbasistoalg(F.bnf, P.pr_get_gen()))
    deg = int(pari.poldegree(F.pol))
    cls = []          # list of distinct classes (pairs)

    def same(c, d):
        return F.local_square(c[0]*d[0], P) and F.local_square(c[1]*d[1], P)

    def insert(c):
        if not any(same(c, d) for d in cls):
            # close under products
            new = [c] + [(c[0]*d[0], c[1]*d[1]) for d in cls]
            for n in new:
                if not any(same(n, d) for d in cls):
                    cls.append(n)

    cls.append((F.M(1), F.M(1)))
    for x in es:
        insert(kummer(x, es, F))
    tries = 0
    while len(cls) < target:
        tries += 1
        if tries > 200000:
            raise ArithmeticError(f'local image at {p} stuck at {len(cls)} < {target}')
        k = rng.randrange(-6, 4)
        x = F.M(sum(rng.randrange(-60, 60)*pari(F.var)**j for j in range(deg))) * pi**k
        fx = (x - es[0])*(x - es[1])*(x - es[2])
        if fx == 0 or not F.local_square(fx, P):
            continue
        insert(kummer(x, es, F))
    return cls, target


def selmer(F, es, primes, seed=1):
    rng = random.Random(seed)
    basis = F.selmer_basis(primes)
    images = [local_image(F, es, P, rng)[0] for P in primes]
    elems = []
    for bits in product((0, 1), repeat=len(basis)):
        g = F.M(1)
        for b, x in zip(bits, basis):
            if b:
                g *= x
        elems.append(g)
    sel = []
    for b1 in elems:
        for b2 in elems:
            ok = True
            for P, img in zip(primes, images):
                if not any(F.local_square(b1*c[0], P) and F.local_square(b2*c[1], P) for c in img):
                    ok = False
                    break
            if ok:
                sel.append((b1, b2))
    return sel, basis
